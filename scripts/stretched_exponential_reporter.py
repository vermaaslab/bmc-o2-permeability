#!/usr/bin/env python3
"""Fit a stretched exponential, A(t) = a*exp(-b*t^c), INDEPENDENTLY to every
absorbance trace (no shared parameters, no ODE, no shell-type grouping), and
emit a LaTeX table of the fitted a, b, c for every replicate.

This is a model-free companion to fit_groups.py: fit_groups.py fits the
mechanistic two-compartment ODE with parameters shared within a shell group;
this script fits only the phenomenological curve shape to each trace on its
own, which is the reference the ODE fits are checked against (see the
"implied c" diagnostic in fit_groups.py, and Table~\ref{tab:perreplicate} in
the manuscript, which reports c and tau from the same per-replicate fits).

Every fit uses a bounded nonlinear least squares (scipy.optimize.curve_fit)
with covariance-based standard errors, and a fixed initial guess scheme
(p0 = [y[0], 1.0, 0.9]) chosen because it converges for every replicate in
this dataset without per-replicate tuning -- verified below by checking
`success`-equivalent (a raised RuntimeError) for every trace rather than
assuming convergence silently.

Usage:
    python scripts/stretched_exponential_reporter.py

Outputs (written to results/):
    abc_fits.json      -- every fitted value and its standard error, plain JSON
    abctable.tex       -- \\input{}-able LaTeX table of a, b, c per replicate
    ctautable.tex      -- \\input{}-able LaTeX table of c and tau only
                          (Table 1 of the manuscript, label tab:perreplicate)
"""
import json
import os
import sys

import numpy as np
from scipy.optimize import curve_fit

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import load_alldata, result_path


def stretched_exp(t, a, b, c):
    return a * np.exp(-b * t ** c)


def fit_trace(t, y):
    """Bounded least-squares fit of a*exp(-b*t^c) to one trace.

    Bounds: a>0 (it's an absorbance), 0<b<=100 (b's scale depends on c and
    the time units here are seconds, so 100 comfortably covers anything
    physically sensible for this dataset), 0<c<=1 (c>1 is compressed, not
    stretched, exponential decay and is not a hypothesis this project
    considers -- see the manuscript's discussion of single-file diffusion).
    """
    popt, pcov = curve_fit(stretched_exp, t, y, p0=[y[0], 1.0, 0.9],
                           bounds=(0, [np.inf, 100.0, 1.0]), maxfev=40000)
    perr = np.sqrt(np.diag(pcov))
    return popt, perr


# Wiffle replicates whose OWN unconstrained fit returns c=1 (to within this
# tolerance) are classified "wiffle, single exp."; the rest are "wiffle,
# stretched". This is the exact threshold fit_groups.py uses to build its
# capped/wiffle_str/wiffle_exp groups for Table 2 -- reproduced here (not
# imported, since this script is meant to stand alone) so the group averages
# in this table always agree with that classification instead of drifting
# from it.
WIFFLE_EXP_C_THRESHOLD = 0.999


def classify(shell, c):
    if shell == "Capped":
        return "capped"
    return "wiffle_exp" if c > WIFFLE_EXP_C_THRESHOLD else "wiffle_str"


GROUP_LABEL = {"capped": "Capped", "wiffle_str": "Wiffle, stretched",
              "wiffle_exp": "Wiffle, single exp."}
GROUP_ORDER = ["capped", "wiffle_str", "wiffle_exp"]


def _num(val, sig=3):
    """Render a number for LaTeX math mode, converting Python's 'e-05'
    exponent form into \\times 10^{-5} so it typesets correctly."""
    s = "%.*g" % (sig, val)
    if "e" in s or "E" in s:
        mant, exp = s.lower().split("e")
        return r"%s{\times}10^{%d}" % (mant, int(exp))
    return s


def fmt(val, err, sig=3):
    """val +/- err, or just val if the covariance was singular (err is nan).

    An error that is a negligible fraction of the value carries no
    information at this precision (it happens for c pinned at the c=1 bound,
    where curve_fit reports a ~1e-8 standard error); print the value alone
    rather than an uncertainty that would mislead.
    """
    if err is None or not np.isfinite(err):
        return "$%s$" % _num(val, sig)
    if val != 0 and abs(err / val) < 1e-4:
        return "$%s$" % _num(val, sig)
    return r"$%s\pm%s$" % (_num(val, sig), _num(err, sig))


def fmt_mean(vals, sig=3):
    """mean +/- sample standard deviation across replicates (not a fit
    standard error -- this is between-replicate scatter, the same convention
    Table~\\ref{tab:perreplicate} in the manuscript uses for the capped mean
    c). Undefined (a single dash) for a group of one."""
    v = np.asarray(vals, dtype=float)
    if len(v) < 2:
        return "$%s$" % _num(v[0], sig) if len(v) == 1 else "---"
    return fmt(v.mean(), v.std(ddof=1), sig)


def render_table(rows):
    """rows: list of dicts with date, shell, group, a, a_err, b, b_err, c, c_err."""
    L = [r"% Generated by stretched_exponential_reporter.py -- do not edit by hand.",
         r"\begin{table}", r"\centering",
         r"\caption{\label{tab:abcfits}Stretched-exponential fit "
         r"$A(t)=a\exp(-bt^{c})$ to every absorbance trace independently "
         r"(no parameters shared between replicates). Uncertainties on "
         r"individual fits are covariance-based standard errors from the "
         r"nonlinear least-squares fit to that trace alone; uncertainties on "
         r"the group averages are the standard deviation across that group's "
         r"replicates, which reflects real replicate-to-replicate variation "
         r"and is typically much larger than any individual fit's standard "
         r"error. Wiffle replicates are split into ``stretched'' and "
         r"``single exp.''\ by whether their own fitted $c$ exceeds %.3f, "
         r"the same threshold used to build the shell groups in "
         r"Table~\ref{tab:odeparams}.}" % WIFFLE_EXP_C_THRESHOLD,
         r"\begin{tabular}{llccc}", r"\toprule",
         r"Shell type & Replicate & $a$ & $b$ & $c$ \\", r"\midrule"]

    prev_shell = None
    by_group = {g: [] for g in GROUP_ORDER}
    for r in rows:
        shell_cell = r["shell"] if r["shell"] != prev_shell else ""
        prev_shell = r["shell"]
        L.append(r"%s & %s & %s & %s & %s \\" % (
            shell_cell, r["date"],
            fmt(r["a"], r["a_err"]), fmt(r["b"], r["b_err"]), fmt(r["c"], r["c_err"])))
        by_group[r["group"]].append(r)

    L.append(r"\midrule")
    for g in GROUP_ORDER:
        grp = by_group[g]
        if not grp:
            continue
        L.append(r"%s (mean, $n=%d$) & & %s & %s & %s \\" % (
            GROUP_LABEL[g], len(grp),
            fmt_mean([x["a"] for x in grp]),
            fmt_mean([x["b"] for x in grp]),
            fmt_mean([x["c"] for x in grp])))

    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(L) + "\n"


def render_ctau_table(rows):
    """Compact table: replicate, c, tau only -- no a or b (Table 1).

    Group label per shell type; geometric-mean tau, since tau is set by a
    multiplicative rate process; capped-mean c uncertainty as the
    between-replicate standard deviation; and a single combined wiffle tau row
    spanning both wiffle sub-groups.
    """
    row_label = {"capped": "Capped", "wiffle_str": "Wiffle (stretched)",
                "wiffle_exp": "Wiffle (single exp.)"}
    # render_table() (the a/b/c table) sorts by raw shell label, which is fine
    # there since it only distinguishes Capped/Wiffle. This table additionally
    # distinguishes the two wiffle sub-groups, so re-sort by classification
    # group (not by date) or the two sub-groups interleave and the repeated-
    # label blanking below never triggers.
    group_order = {"capped": 0, "wiffle_str": 1, "wiffle_exp": 2}
    rows = sorted(rows, key=lambda r: (group_order[r["group"]], r["date"]))
    L = [r"% Generated by stretched_exponential_reporter.py -- do not edit by hand.",
         r"\begin{table}", r"\centering",
         r"\caption{\label{tab:perreplicate}Per-replicate stretched-exponential "
         r"fits, $A_{780nm}=a\exp\left(-b t^c\right)$, performed independently "
         r"on each absorbance trace with no shared parameters. Uncertainties "
         r"on $c$ are the covariance-based standard errors from the "
         r"individual nonlinear least-squares fit. $\tau=b^{-1/c}$ is the "
         r"characteristic $1/e$ decay time. Wiffle replicates are grouped by "
         r"whether the unconstrained fit returned $c=1$ (single exponential) "
         r"or $c<1$ (stretched); this classification is the result of the "
         r"fit, not an input to it. Reported means for $\tau$ are the "
         r"geometric mean. Uncertainties on aggregated $c$ values are the "
         r"standard deviation across replicates.}",
         r"\begin{tabular}{llcc}", r"\toprule",
         r"Shell type & Replicate & $c$ & $\tau$ (s) \\", r"\midrule"]

    prev_group = None
    for r in rows:
        label = row_label[r["group"]]
        gcell = label if label != prev_group else ""
        prev_group = label
        L.append(r"%s & %s & $%.3f\pm%.3f$ & %.0f \\" % (
            gcell, r["date"], r["c"], r["c_err"], r["tau"]))

    L.append(r"\midrule")
    c_capped = [r["c"] for r in rows if r["group"] == "capped"]
    tau_capped = [r["tau"] for r in rows if r["group"] == "capped"]
    tau_wiffle = [r["tau"] for r in rows if r["group"] in ("wiffle_str", "wiffle_exp")]
    if c_capped:
        gmean_capped = float(10 ** np.mean(np.log10(tau_capped)))
        L.append(r"Capped (mean) & $n=%d$ & $%.3f\pm%.3f$ & %.0f$^{\dagger}$ \\" % (
            len(c_capped), np.mean(c_capped),
            np.std(c_capped, ddof=1) if len(c_capped) > 1 else 0.0, gmean_capped))
    if tau_wiffle:
        gmean_wiffle = float(10 ** np.mean(np.log10(tau_wiffle)))
        L.append(r"Wiffle (mean) & $n=%d$ & --- & %.0f$^{\dagger}$ \\" % (
            len(tau_wiffle), gmean_wiffle))

    L += [r"\bottomrule", r"\end{tabular}", "", r"\vspace{1ex}",
          r"{\footnotesize $^{\dagger}$Geometric mean, appropriate because "
          r"$\tau$ is set by a multiplicative rate process; uncertainty on "
          r"the capped mean $c$ is the standard deviation across replicates, "
          r"which exceeds the per-fit standard error by roughly an order of "
          r"magnitude.}",
          r"\end{table}"]
    return "\n".join(L) + "\n"


def main():
    alldata = load_alldata()

    rows = []
    n_failed = 0
    # Sort by shell type first (Capped before Wiffle) so the table reads like
    # Table 1 in the manuscript, then by date within each shell type.
    keys = [(shell, date) for date in alldata for shell in alldata[date]]
    for shell, date in sorted(keys):
        t, y = alldata[date][shell]
        try:
            (a, b, c), (a_e, b_e, c_e) = fit_trace(t, y)
        except Exception as exc:
            print("FAILED to fit %s %s: %s" % (date, shell, exc), file=sys.stderr)
            n_failed += 1
            continue
        tau = float(b ** (-1.0 / c))  # characteristic 1/e decay time
        rows.append(dict(date=date, shell=shell, group=classify(shell, c),
                         a=float(a), a_err=float(a_e),
                         b=float(b), b_err=float(b_e),
                         c=float(c), c_err=float(c_e),
                         tau=tau))
        print("%-11s %-7s  a=%.4g+/-%.2g  b=%.4g+/-%.2g  c=%.4f+/-%.4f"
              % (date, shell, a, a_e, b, b_e, c, c_e))

    if n_failed:
        print("WARNING: %d/%d traces failed to fit -- see stderr above; "
              "table is incomplete" % (n_failed, len(keys)), file=sys.stderr)

    with open(result_path("abc_fits.json"), "w") as fh:
        json.dump(rows, fh, indent=2)

    with open(result_path("abctable.tex"), "w") as fh:
        fh.write(render_table(rows))

    with open(result_path("ctautable.tex"), "w") as fh:
        fh.write(render_ctau_table(rows))

    print("\nWrote results/abc_fits.json, abctable.tex, ctautable.tex (%d replicates%s)"
          % (len(rows), ", %d FAILED" % n_failed if n_failed else ""))


if __name__ == "__main__":
    sys.exit(main())
